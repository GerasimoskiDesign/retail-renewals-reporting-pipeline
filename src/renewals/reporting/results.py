"""Compute the README numbers (naive vs fixed) and write charts + ``docs/results.md``."""

from __future__ import annotations

import datetime as dt
import logging
from pathlib import Path

import pandas as pd

from renewals.downloader.naming import month_folder
from renewals.pipeline import compute_month
from renewals.reporting.charts import naive_vs_fixed_chart, volume_chart
from renewals.settings import Settings
from renewals.validation.checks import ReportBundle, validate
from renewals.world.generator import World

log = logging.getLogger(__name__)


def _totals(bundle: ReportBundle, start: dt.date | None = None, end: dt.date | None = None) -> dict:
    sd = bundle.shop_day
    if start:
        sd = sd[(sd["day"] >= pd.Timestamp(start)) & (sd["day"] <= pd.Timestamp(end))]
    combined, digital = int(sd["combined"].sum()), int(sd["digital"].sum())
    over = sd[sd["digital"] > sd["combined"]]
    return {
        "combined": combined,
        "digital": digital,
        "share": digital / combined if combined else float("nan"),
        "over_100": len(over),
        "worst": float(sd.loc[sd["combined"] > 0, "digital_share"].max()),
    }


def _md_table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def build_results(settings: Settings, month: dt.date, as_of: dt.date, real: bool = False) -> Path:
    world = World.load(settings.world_dir)
    root = settings.download_root(real)
    naive, _ = compute_month(root, month, as_of, mode="naive")
    fixed, result = compute_month(root, month, as_of, mode="fixed")
    assert result is not None
    v_naive, v_fixed = validate(naive), validate(fixed)
    campaign = (world.cfg.campaign_start, world.cfg.campaign_end)

    img = settings.docs_img_dir
    naive_vs_fixed_chart(naive, fixed, campaign, img / "naive_vs_fixed_digital_share.png")
    volume_chart(result.facts, campaign, img / "daily_volume_by_channel.png")

    def fmt(x: float) -> str:
        return f"{x:.1%}"

    rows = []
    for label, s, e in (("Whole month", None, None), ("Campaign week", *campaign)):
        n, f = _totals(naive, s, e), _totals(fixed, s, e)
        rows += [
            [label, "Combined gross adds", f"{n['combined']:,}", f"{f['combined']:,}"],
            [label, "Digital gross adds", f"{n['digital']:,}", f"{f['digital']:,}"],
            [label, "Digital share", fmt(n["share"]), fmt(f["share"])],
            [label, "Shop/days with share > 100%", str(n["over_100"]), str(f["over_100"])],
            [label, "Highest shop/day share", fmt(n["worst"]), fmt(f["worst"])],
        ]
    dup_naive = next(r for r in v_naive.results if r.name == "no_contract_counted_twice")
    rows.append(
        ["Whole month", "Contracts counted more than once", f"{dup_naive.violations:,}", "0"]
    )

    a = result.audit
    recon = [
        ["Source rows (Contract Renewals + Tariff Migrations)", f"{a['source_rows']:,}"],
        ["Duplicate rows (same process delivered twice)", f"{a['duplicate_rows']:,}"],
    ]
    recon += [[f"Excluded: `{k}`", f"{v:,}"] for k, v in a["excluded"].items()]
    recon.append(["**Counted gross adds**", f"**{a['counted']:,}**"])

    p = world.processes
    world_rows = [
        [
            "Regions / shops / agents",
            f"{world.shops['region_id'].nunique()} / {len(world.shops)} / {len(world.agents)}",
        ],
        [
            "Process starts simulated",
            f"{len(p):,} ({world.cfg.start:%d.%m} - {world.cfg.end:%d.%m.%Y})",
        ],
        ["Campaign week", f"{campaign[0]:%d.%m} - {campaign[1]:%d.%m.%Y}"],
    ]
    md = (
        "\n\n".join(
            [
                f"# Results on synthetic data ({month_folder(month)}, as of {as_of:%d.%m.%Y})",
                "Generated by `python -m renewals results`. All numbers come from the seeded "
                "synthetic world (seed 42), not from any real business.",
                "## Synthetic world",
                _md_table(["", "Value"], world_rows),
                "## Naive vs fixed logic",
                _md_table(["Period", "Metric", "Naive", "Fixed"], rows),
                "## Reconciliation (fixed logic)",
                _md_table(["Step", "Rows"], recon),
                "## Validation",
                "```text\n" + v_naive.summary() + "\n\n" + v_fixed.summary() + "\n```",
            ]
        )
        + "\n"
    )
    out = settings.root / "docs" / "results.md"
    out.write_text(md, encoding="utf-8")
    log.info("Wrote %s", out)
    return out
